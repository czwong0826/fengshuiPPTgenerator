# 数据结构说明：
# ROOM_KNOWLEDGE_BASE 里每个区域对应一个列表，列表里的每一项可以是：
#   1. 一个普通字符串 —— 渲染成一个普通 checkbox，勾选后原样作为最终文案。
#   2. 一个 "选择型" 条目（用 C(...) 构造）—— 渲染成一个 checkbox + 若干子选项
#      （st.radio 单选 或 st.multiselect 多选）。勾选主选项并选完子选项后，
#      用 template.format(**选中的值) 拼出最终文案。
#      例如 C("床頭後方顔色宜多用：{color}", ..., color=COLOR_OPTIONS)
#      勾选后选择 "火色-淺紅、粉紅、紫、橙色"，最终文案就是：
#      "床頭後方顔色宜多用：火色-淺紅、粉紅、紫、橙色"

# ---------- 共用的颜色子选项 ----------
COLOR_OPTIONS = [
    "木色-淺綠色",
    "火色-淺紅、粉紅、紫、橙色",
    "土色-淺奶白、褐、黃色",
    "金色-淺金、銀、白色",
    "水色-淺灰、藍色",
    "亮色爲主",
]


def C(template: str, label: str, **groups) -> dict:
    """构造一个"选择型"条目。

    template: 最终文案模板，用 {key} 占位。
    label: 勾选框上显示的文字（一般是模板里去掉占位符后的前半句）。
    groups: 每个占位符对应的选项列表。
        - 普通传参 key=[...] -> 单选（st.radio）。
        - 传 key=("multi", [...]) -> 多选（st.multiselect），
          多个选中值会用「、」拼接后再填入模板。
    """
    choices = {}
    for key, val in groups.items():
        if isinstance(val, tuple) and len(val) == 2 and val[0] == "multi":
            choices[key] = {"options": val[1], "multi": True}
        else:
            choices[key] = {"options": val, "multi": False}
    return {"label": label, "template": template, "choices": choices}


